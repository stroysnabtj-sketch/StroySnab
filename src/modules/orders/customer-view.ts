import type { FullOrder } from "./service";
export function customerOrderView(order: FullOrder) {
  return {
    id: order.id,
    orderNumber: order.orderNumber,
    customerName: order.customerName,
    customerPhone: order.customerPhone,
    deliveryCity: order.deliveryCity,
    deliveryAddress: order.deliveryAddress,
    deliveryLat: order.deliveryLat,
    deliveryLng: order.deliveryLng,
    deliveryNotes: order.deliveryNotes,
    vehicleType: order.vehicleType,
    unloadingType: order.unloadingType,
    preferredDeliveryDate: order.preferredDeliveryDate,
    preferredTimeSlot: order.preferredTimeSlot,
    status: order.status,
    paymentMethod: order.paymentMethod,
    materialsTotalDirams: order.materialsTotalDirams,
    deliveryTotalDirams: order.deliveryTotalDirams,
    totalDirams: order.totalDirams,
    estimatedWeightKg: order.estimatedWeightKg,
    estimatedVolumeM3: order.estimatedVolumeM3,
    driverName: order.driverName,
    driverPhone: order.driverPhone,
    vehiclePlate: order.vehiclePlate,
    createdAt: order.createdAt,
    updatedAt: order.updatedAt,
    history: order.history,
    items: order.items.map((item) => ({
      id: item.id,
      productName: item.productName,
      sku: item.sku,
      unit: item.unit,
      qty: item.qty,
      priceDirams: item.priceDirams,
      subtotalDirams: item.subtotalDirams,
      supplierName: item.supplierName,
    })),
  };
}
